# =============================================================================
# Merges the template outputs of all models into one file.
#
#   Rscript scripts/merge_template_outputs.R
#
# Reads   : outputs/<Model>/<Model>_GLOBIOM_comprehensive.csv
#           outputs/<Model>/proposed_glossary_additions.csv (if present)
# Output  : outputs/merged/AllModels_GLOBIOM_comprehensive.csv
#           outputs/merged/proposed_glossary_additions.csv
#           outputs/merged/README.md
#
# Run the four converters first. Values are copied unchanged; the merged file
# is re-validated with the union of the models' declared additions.
# =============================================================================

find_root <- function(d = normalizePath(getwd(), winslash = "/")) {
  while (!file.exists(file.path(d, "AgEnRes_R.Rproj"))) {
    p <- dirname(d)
    if (p == d) stop("Project root (AgEnRes_R.Rproj) not found above ", getwd())
    d <- p
  }
  d
}
ROOT <- find_root()
source(file.path(ROOT, "scripts", "shared_conversion_helpers.R"))

MODELS      <- c("GLOBIOM", "FarmDyn", "AgriPolis", "OpenPROM")
OUT_DIR_REL <- file.path("outputs", "merged")
OUT_CSV     <- "AllModels_GLOBIOM_comprehensive.csv"

# Model-specific Region / Year values authorised in the individual converters.
REGION_REGEX <- "^AgriPolis_r[0-9]+_f[0-9]+_"   # AgriPolis farm IDs
YEAR_REGEX   <- "^[0-9]{4}$"                    # annual years (AgriPolis, OpenPROM)

log_msg("== merge ==")
vocab <- load_template_vocab(ROOT)

parts <- list(); adds <- list()
for (m in MODELS) {
  f <- file.path(ROOT, "outputs", m, paste0(m, "_GLOBIOM_comprehensive.csv"))
  if (!file.exists(f)) stop("Missing output of ", m, ": ", f, " - run scripts/", m, "_to_template.R first.")
  d <- read_template_output(f, vocab$columns)
  if (!identical(names(d), vocab$columns)) stop(m, ": unexpected columns in ", f)
  if (!all(d$Model == m)) stop(m, ": Model column does not equal '", m, "' in ", f)
  log_msg("  %-9s %9d rows", m, nrow(d))
  parts[[m]] <- d
  a <- file.path(dirname(f), "proposed_glossary_additions.csv")
  if (file.exists(a)) adds[[m]] <- fread(a, colClasses = "character")
}
merged <- rbindlist(parts)
additions <- if (length(adds)) {
  rbindlist(adds)[, .(definition = definition[1], source_label = paste(unique(source_label), collapse = "; "),
                      model = paste(unique(model), collapse = "; ")), by = .(dimension, code)]
} else NULL

out_dir <- file.path(ROOT, OUT_DIR_REL)
res <- validate_and_write(merged, vocab, file.path(out_dir, OUT_CSV), additions = additions,
                          allowed_region_regex = REGION_REGEX, allowed_year_regex = YEAR_REGEX)

overview <- merged[, .(rows = .N, scenarios = paste(unique(Scenario), collapse = ", "),
                       regions = uniqueN(Region), years = paste(range(as.integer(Year)), collapse = "-"),
                       variables = paste(sort(unique(Variable)), collapse = ", ")), by = Model]
shared <- merged[, .(models = paste(sort(unique(Model)), collapse = ", ")), by = .(Variable)][order(Variable)]

readme <- c(
  "# All models in the common GLOBIOM-style reporting format",
  "",
  "_Generated by `scripts/merge_template_outputs.R` - do not edit by hand; rerun the script instead._",
  "",
  sprintf("- File: `%s` - %d rows, columns `%s`.", file.path(OUT_DIR_REL, OUT_CSV), nrow(merged), paste(vocab$columns, collapse = ", ")),
  "- Row-wise union of the four model outputs; values unchanged. See each model's README for its mappings.",
  "- Comparing models needs care: units differ (e.g. COST in `Euro per ha` vs `USD 2000 per ha`), GLOBIOM COST Items carry a management part, AgriPolis Regions are farms. See `claude_GLOBIOM_AG_REG_conversion_instructions.md` section 6 for the planned crosswalk.",
  "",
  "## Overview by model",
  "",
  md_table(overview),
  "",
  "## Variables by model",
  "",
  md_table(shared),
  "",
  "## Proposed glossary additions (all models)",
  "",
  additions_md(res),
  "",
  "## Validation",
  "",
  readme_validation_note(),
  "",
  validation_md(res),
  "",
  "## Reproduction",
  "",
  "```",
  paste0("Rscript scripts/", MODELS, "_to_template.R"),
  "Rscript scripts/merge_template_outputs.R",
  "```"
)
write_lines_lf(readme, file.path(out_dir, "README.md"))
log_msg("== merge done ==")
